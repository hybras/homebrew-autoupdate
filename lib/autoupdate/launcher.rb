# frozen_string_literal: true

require "shellwords"

module Autoupdate
  # The launch agent runs a small launcher script instead of the updater
  # itself. When the bundled app supports it, the launcher opens the app
  # through LaunchServices and the app runs the updater. macOS then holds the
  # signed app, rather than Homebrew's portable Ruby, responsible for App
  # Management checks, so a single grant survives portable Ruby upgrades.
  # See https://github.com/DomT4/homebrew-autoupdate/issues/163.
  module Launcher
    module_function

    # Names the `run-updater` arguments this launcher passes. Give a changed
    # argument list a new name and keep the app accepting the old one, since
    # launchers are only regenerated by `brew autoupdate start`.
    CAPABILITY = "run-updater-1"
    SCRIPT_NAME = "brew_autoupdate_launcher"

    def path(location)
      File.join(location, SCRIPT_NAME)
    end

    def app_supports_run_updater?(app)
      info_plist = File.join(app, "Contents", "Info.plist")
      return false unless File.exist?(info_plist)

      output = IO.popen(
        ["/usr/bin/plutil", "-extract", "BrewAutoupdateCapabilities", "json", "-o", "-", info_plist],
        err: File::NULL,
        &:read
      )
      Process.last_status.success? && output.include?("\"#{CAPABILITY}\"")
    end

    def script(app:, location:, log:, open: "/usr/bin/open")
      <<~SH
        #!/bin/sh
        # Generated by `brew autoupdate start`; rewritten on every start.
        app=#{Shellwords.escape(app)}
        updater=#{Shellwords.escape(File.join(location, "brew_autoupdate"))}
        status_file=#{Shellwords.escape(File.join(location, "brew_autoupdate.status"))}

        # An app without updater support (e.g. an older checkout) runs the
        # updater directly, as before.
        if ! /usr/bin/plutil -extract BrewAutoupdateCapabilities json -o - \\
            "$app/Contents/Info.plist" 2>/dev/null | /usr/bin/grep -q '"#{CAPABILITY}"'
        then
          exec "$updater"
        fi

        # The app stops the updater when this script exits, so `brew autoupdate
        # stop` still stops a running update.
        /bin/rm -f "$status_file"
        if ! #{open} -W -g -n "$app" --args run-updater #{Shellwords.escape(log)} "$$"
        then
          echo "Warning: could not open $app; running the updater directly." >&2
          exec "$updater"
        fi

        status=$(/bin/cat "$status_file" 2>/dev/null)
        exit "${status:-1}"
      SH
    end
  end
end
